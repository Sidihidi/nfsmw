int FEngMapJoyParamToJoyport(int feng_param) {
    if (feng_param & 1) {
        return 0;
    }
    if (feng_param & 2) {
        return 1;
    }
    if (feng_param & 4) {
        return 2;
    }
    if (feng_param & 8) {
        return 3;
    }
    return -1;
}

int FEngMapJoyportToJoyParam(int joyport) {
    if (joyport == 0)
        return 1;
    if (joyport == 1)
        return 2;
    if (joyport == 2)
        return 4;
    if (joyport == 3)
        return 8;
    return 0;
}

void FEngSNMakeHidden(char *outBuffer, int32 out_buf_size, const char *strInput) {
    int len = bStrLen(strInput);
    int i = 0;
    if (i < len) {
        int max = out_buf_size - 1;
        if (i != max) {
            do {
                outBuffer[i] = '*';
                i++;
                if (i >= len) {
                    break;
                }
            } while (i != max);
        }
    }
    outBuffer[i] = 0;
}

